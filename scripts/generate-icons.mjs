#!/usr/bin/env node
/**
 * A.I.M. icon generator.
 *
 * Produces every raster asset the desktop app and the installers need from one
 * parametric description of the brand mark: a black rounded square with a teal
 * mouse-pointer arrow, white outline, subtle inner shadow and a faint teal glow.
 *
 *   node scripts/generate-icons.mjs                 # built-in renderer (no dependencies)
 *   node scripts/generate-icons.mjs --renderer=sharp # rasterise the SVG with `sharp` if installed
 *
 * Outputs (assets/icons/):
 *   aim.svg, aim-mono.svg                                   vector sources
 *   icon.png (1024) icon-512/256/128/64/48/32/16.png        app icon
 *   tray.png (32), tray@1x.png (16), tray@2x.png (32)       tray icon (arrow only, transparent)
 *   trayTemplate.png (16), trayTemplate@2x.png (32)         macOS template (white silhouette)
 *   icon.ico                                                16/24/32/48/64/128/256 PNG-compressed entries
 * and copies icon.ico + icon.png into packages/desktop/build/ for electron-builder.
 *
 * The built-in renderer is the default because it is deterministic and needs no
 * native module: it rasterises the exact geometry used for the SVG with 2-D
 * supersampling and encodes PNGs with node:zlib. Small sizes drop the glow and
 * inner shadow and clamp the outline so the pointer stays crisp at 16 px.
 */
import { mkdir, writeFile, copyFile } from 'node:fs/promises';
import path from 'node:path';
import zlib from 'node:zlib';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'assets', 'icons');
const BUILD = path.join(ROOT, 'packages', 'desktop', 'build');

const args = new Set(process.argv.slice(2));
const rendererArg = [...args].find((a) => a.startsWith('--renderer='));
const RENDERER = rendererArg ? rendererArg.split('=')[1] : 'builtin';

// ─── brand ──────────────────────────────────────────────────────────────────
const C = {
  black: '#0B0B0D',
  surface: '#141417',
  teal: '#1ABFB0',
  tealBright: '#2EE6D6',
  tealDim: '#128C82',
  white: '#FFFFFF',
};

// ─── geometry (in a 1024 × 1024 design space) ───────────────────────────────
const SIDE = 1024;
const CORNER_RADIUS = 0.22 * SIDE; // ≈ 225

// Classic pointer silhouette, unit coordinates (tip at the origin, height ≈ 19.6).
const ARROW_UNIT = [
  [0, 0],
  [0, 17.0],
  [4.3, 13.2],
  [7.3, 19.6],
  [10.4, 18.2],
  [7.5, 11.9],
  [13.0, 11.9],
];
const ARROW_UNIT_W = 13.0;
const ARROW_UNIT_H = 19.6;

// Stockier variant for 16–32 px: shorter shaft, wider tail, so the silhouette survives downsampling.
const ARROW_UNIT_SMALL = [
  [0, 0],
  [0, 16.4],
  [4.4, 12.8],
  [7.0, 19.4],
  [11.0, 17.7],
  [8.1, 11.7],
  [13.0, 11.7],
];
const ARROW_UNIT_SMALL_H = 19.4;

/**
 * Place the arrow so that its bounding box is centred, with `heightFrac` of the side.
 * `snap` rounds the origin (tip and left edge) to whole pixels so the vertical edge is crisp.
 */
function arrowPoints(side, heightFrac, dx = 0, dy = 0, { small = false, snap = false } = {}) {
  const unit = small ? ARROW_UNIT_SMALL : ARROW_UNIT;
  const unitH = small ? ARROW_UNIT_SMALL_H : ARROW_UNIT_H;
  const scale = (side * heightFrac) / unitH;
  const w = ARROW_UNIT_W * scale;
  const h = unitH * scale;
  let ox = (side - w) / 2 + dx * side;
  let oy = (side - h) / 2 + dy * side;
  if (snap) {
    ox = Math.round(ox);
    oy = Math.round(oy);
  }
  return unit.map(([x, y]) => [ox + x * scale, oy + y * scale]);
}

const APP = { heightFrac: 0.56, dx: 0.012, dy: 0.0, strokeFrac: 0.02 }; // 20 px outline at 1024
const APP_SMALL = { heightFrac: 0.66, dx: 0.02, dy: 0.0, strokeFrac: 0.02 }; // ≤ 32 px
const TRAY = { heightFrac: 0.84, dx: 0.0, dy: 0.0, strokeFrac: 0.07 };

// ─── SVG sources ────────────────────────────────────────────────────────────
function pointsAttr(pts) {
  return pts.map(([x, y]) => `${round(x)},${round(y)}`).join(' ');
}
function round(n) {
  return Math.round(n * 100) / 100;
}

function buildAppSvg() {
  const pts = arrowPoints(SIDE, APP.heightFrac, APP.dx, APP.dy);
  const sw = APP.strokeFrac * SIDE;
  const ys = pts.map((p) => p[1]);
  const top = Math.min(...ys);
  const bottom = Math.max(...ys);
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- A.I.M. — Artificial Intelligence Management. Brand mark, 1024 design space. Generated by scripts/generate-icons.mjs -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SIDE} ${SIDE}" width="${SIDE}" height="${SIDE}">
  <defs>
    <linearGradient id="bg" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="${C.surface}"/>
      <stop offset="1" stop-color="${C.black}"/>
    </linearGradient>
    <linearGradient id="arrow" gradientUnits="userSpaceOnUse" x1="0" y1="${round(top)}" x2="0" y2="${round(bottom)}">
      <stop offset="0" stop-color="${C.tealBright}"/>
      <stop offset="1" stop-color="${C.teal}"/>
    </linearGradient>
    <filter id="glow" x="-50%" y="-50%" width="200%" height="200%">
      <feGaussianBlur stdDeviation="${round(SIDE * 0.04)}"/>
    </filter>
    <filter id="innerShadow" x="-20%" y="-20%" width="140%" height="140%">
      <feOffset dx="${round(-SIDE * 0.012)}" dy="${round(-SIDE * 0.016)}"/>
      <feGaussianBlur stdDeviation="${round(SIDE * 0.012)}" result="blur"/>
      <feComposite operator="arithmetic" k2="-1" k3="1" in="SourceGraphic" in2="blur" result="inner"/>
      <feFlood flood-color="${C.tealDim}" flood-opacity="0.9"/>
      <feComposite operator="in" in2="inner"/>
      <feComposite operator="over" in2="SourceGraphic"/>
    </filter>
    <clipPath id="square"><rect width="${SIDE}" height="${SIDE}" rx="${round(CORNER_RADIUS)}"/></clipPath>
  </defs>
  <rect width="${SIDE}" height="${SIDE}" rx="${round(CORNER_RADIUS)}" fill="url(#bg)"/>
  <rect x="2" y="2" width="${SIDE - 4}" height="${SIDE - 4}" rx="${round(CORNER_RADIUS - 2)}" fill="none" stroke="${C.white}" stroke-opacity="0.06" stroke-width="4"/>
  <g clip-path="url(#square)">
    <polygon points="${pointsAttr(pts)}" fill="${C.tealBright}" opacity="0.35" filter="url(#glow)"/>
  </g>
  <polygon points="${pointsAttr(pts)}" fill="none" stroke="${C.white}" stroke-width="${round(sw * 2)}" stroke-linejoin="round"/>
  <polygon points="${pointsAttr(pts)}" fill="url(#arrow)" filter="url(#innerShadow)"/>
</svg>
`;
}

function buildMonoSvg() {
  const pts = arrowPoints(SIDE, TRAY.heightFrac, TRAY.dx, TRAY.dy);
  const sw = TRAY.strokeFrac * SIDE;
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- A.I.M. monochrome mark (tray / template image). Single colour: recolour by changing the fill. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${SIDE} ${SIDE}" width="${SIDE}" height="${SIDE}">
  <polygon points="${pointsAttr(pts)}" fill="${C.white}" stroke="${C.white}" stroke-width="${round(sw * 2)}" stroke-linejoin="round"/>
</svg>
`;
}

// ─── built-in rasteriser ────────────────────────────────────────────────────
function hex(c) {
  return [parseInt(c.slice(1, 3), 16), parseInt(c.slice(3, 5), 16), parseInt(c.slice(5, 7), 16)];
}
const RGB = Object.fromEntries(Object.entries(C).map(([k, v]) => [k, hex(v)]));

function mix(a, b, t) {
  return [a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t, a[2] + (b[2] - a[2]) * t];
}

/** Signed distance to a rounded box centred at (cx, cy) with half size h and radius r (negative inside). */
function roundedBoxSdf(px, py, cx, cy, h, r) {
  const qx = Math.abs(px - cx) - (h - r);
  const qy = Math.abs(py - cy) - (h - r);
  const ox = Math.max(qx, 0);
  const oy = Math.max(qy, 0);
  return Math.hypot(ox, oy) + Math.min(Math.max(qx, qy), 0) - r;
}

function segDist(px, py, ax, ay, bx, by) {
  const vx = bx - ax;
  const vy = by - ay;
  const wx = px - ax;
  const wy = py - ay;
  const len2 = vx * vx + vy * vy;
  let t = len2 > 0 ? (wx * vx + wy * vy) / len2 : 0;
  t = t < 0 ? 0 : t > 1 ? 1 : t;
  const dx = ax + vx * t - px;
  const dy = ay + vy * t - py;
  return Math.hypot(dx, dy);
}

/** Pre-compute edges and outward normals for a polygon. */
function preparePolygon(pts) {
  let area = 0;
  for (let i = 0; i < pts.length; i++) {
    const [x1, y1] = pts[i];
    const [x2, y2] = pts[(i + 1) % pts.length];
    area += x1 * y2 - x2 * y1;
  }
  const cw = area < 0; // in screen space (y down), negative signed area = clockwise
  const edges = pts.map((p, i) => {
    const q = pts[(i + 1) % pts.length];
    const ex = q[0] - p[0];
    const ey = q[1] - p[1];
    const len = Math.hypot(ex, ey) || 1;
    // outward normal: rotate edge direction; sign depends on orientation
    let nx = ey / len;
    let ny = -ex / len;
    if (!cw) {
      nx = -nx;
      ny = -ny;
    }
    return { ax: p[0], ay: p[1], bx: q[0], by: q[1], nx, ny };
  });
  const xs = pts.map((p) => p[0]);
  const ys = pts.map((p) => p[1]);
  return { pts, edges, minX: Math.min(...xs), maxX: Math.max(...xs), minY: Math.min(...ys), maxY: Math.max(...ys) };
}

function insidePolygon(px, py, poly) {
  let inside = false;
  const { pts } = poly;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
    const [xi, yi] = pts[i];
    const [xj, yj] = pts[j];
    if (yi > py !== yj > py && px < ((xj - xi) * (py - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

/** Nearest edge distance and index. */
function polygonDist(px, py, poly) {
  let best = Infinity;
  let idx = 0;
  const { edges } = poly;
  for (let i = 0; i < edges.length; i++) {
    const e = edges[i];
    const d = segDist(px, py, e.ax, e.ay, e.bx, e.by);
    if (d < best) {
      best = d;
      idx = i;
    }
  }
  return { d: best, idx };
}

/**
 * Render one icon variant.
 * mode: 'app'  — rounded black square + arrow (the application icon)
 *       'tray' — arrow only on transparent background (colour tray icon)
 *       'mono' — arrow silhouette, white, on transparent (template image)
 */
function renderIcon(size, mode) {
  const k = size / SIDE;
  const small = size <= 32;
  const cfg = mode === 'app' ? (small ? APP_SMALL : APP) : TRAY;
  const pts = arrowPoints(size, cfg.heightFrac, cfg.dx, cfg.dy, { small, snap: size <= 64 });
  const poly = preparePolygon(pts);
  const glowOn = mode === 'app' && size >= 128;
  const shadowOn = mode === 'app' && size >= 64;
  // outline: proportional, but never thinner than ~0.9 px so the rim survives at 16 px
  const stroke = Math.max(cfg.strokeFrac * SIDE * k, mode === 'mono' ? 0 : small ? 0.9 : 1.1);
  const ss = size <= 64 ? 8 : size <= 256 ? 5 : size <= 512 ? 4 : 3; // supersampling grid
  const inv = 1 / (ss * ss);
  const radius = CORNER_RADIUS * k;
  const half = size / 2;
  const rimW = Math.max(2 * k * 4, 1.2);
  const glowSigma = 0.075 * size;
  const shadowBand = 0.04 * size;
  const arrowTop = poly.minY;
  const arrowH = poly.maxY - poly.minY;
  const topCol = mix(RGB.teal, RGB.tealBright, 0.6);
  const botCol = RGB.teal;

  const out = Buffer.alloc(size * size * 4);
  let o = 0;
  for (let y = 0; y < size; y++) {
    for (let x = 0; x < size; x++) {
      let R = 0;
      let G = 0;
      let B = 0;
      let A = 0;
      for (let sy = 0; sy < ss; sy++) {
        const py = y + (sy + 0.5) / ss;
        for (let sx = 0; sx < ss; sx++) {
          const px = x + (sx + 0.5) / ss;
          // layer stack for this sample (premultiplied accumulation via source-over)
          let r = 0;
          let g = 0;
          let b = 0;
          let a = 0;
          const over = (c, ca) => {
            const ia = 1 - ca;
            r = c[0] * ca + r * ia;
            g = c[1] * ca + g * ia;
            b = c[2] * ca + b * ia;
            a = ca + a * ia;
          };

          let inSquare = true;
          if (mode === 'app') {
            const sd = roundedBoxSdf(px, py, half, half, half, radius);
            inSquare = sd < 0;
            if (inSquare) {
              const t = py / size;
              over(mix(RGB.surface, RGB.black, t), 1);
              // faint inner rim highlight
              const inner = -sd;
              if (inner < rimW) over(RGB.white, 0.06 * (1 - inner / rimW));
            }
          }

          const inArrow = insidePolygon(px, py, poly);
          const { d, idx } = polygonDist(px, py, poly);

          if (inSquare) {
            if (glowOn && !inArrow) {
              const ga = 0.34 * Math.exp(-d / glowSigma);
              if (ga > 0.003) over(RGB.tealBright, ga);
            }
            if (mode === 'mono') {
              if (inArrow || d <= stroke) over(RGB.white, 1);
            } else {
              if (!inArrow && d <= stroke) over(RGB.white, 1);
              if (inArrow) {
                const t = Math.min(1, Math.max(0, (py - arrowTop) / arrowH));
                let col = mix(topCol, botCol, t);
                if (shadowOn && d < shadowBand) {
                  const n = poly.edges[idx];
                  const facing = Math.max(0, n.nx * 0.45 + n.ny * 0.9); // edges facing down/right
                  const w = facing * (1 - d / shadowBand) * 0.55;
                  col = mix(col, RGB.tealDim, w);
                }
                over(col, 1);
              }
            }
          }
          R += r * inv;
          G += g * inv;
          B += b * inv;
          A += a * inv;
        }
      }
      // un-premultiply
      if (A > 0) {
        out[o++] = clamp8(R / A);
        out[o++] = clamp8(G / A);
        out[o++] = clamp8(B / A);
        out[o++] = clamp8(A * 255);
      } else {
        out[o++] = 0;
        out[o++] = 0;
        out[o++] = 0;
        out[o++] = 0;
      }
    }
  }
  return out;
}

function clamp8(v) {
  return v < 0 ? 0 : v > 255 ? 255 : Math.round(v);
}

// ─── PNG encoder ────────────────────────────────────────────────────────────
const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();
function crc32(buf) {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const td = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(td));
  return Buffer.concat([len, td, crc]);
}
function encodePng(rgba, width, height) {
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 6; // colour type RGBA
  ihdr[10] = 0;
  ihdr[11] = 0;
  ihdr[12] = 0;
  const stride = width * 4;
  const raw = Buffer.alloc((stride + 1) * height);
  for (let y = 0; y < height; y++) {
    raw[y * (stride + 1)] = 0; // filter: none
    rgba.copy(raw, y * (stride + 1) + 1, y * stride, (y + 1) * stride);
  }
  const idat = zlib.deflateSync(raw, { level: 9 });
  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', ihdr),
    chunk('IDAT', idat),
    chunk('IEND', Buffer.alloc(0)),
  ]);
}

// ─── ICO container (PNG-compressed entries, supported since Windows Vista) ───
function encodeIco(entries /* [{size, png}] */) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0); // reserved
  header.writeUInt16LE(1, 2); // type: icon
  header.writeUInt16LE(entries.length, 4);
  const dir = Buffer.alloc(16 * entries.length);
  let offset = 6 + dir.length;
  entries.forEach(({ size, png }, i) => {
    const b = i * 16;
    dir[b] = size >= 256 ? 0 : size;
    dir[b + 1] = size >= 256 ? 0 : size;
    dir[b + 2] = 0; // palette
    dir[b + 3] = 0; // reserved
    dir.writeUInt16LE(1, b + 4); // colour planes
    dir.writeUInt16LE(32, b + 6); // bits per pixel
    dir.writeUInt32LE(png.length, b + 8);
    dir.writeUInt32LE(offset, b + 12);
    offset += png.length;
  });
  return Buffer.concat([header, dir, ...entries.map((e) => e.png)]);
}

// ─── optional sharp renderer ────────────────────────────────────────────────
async function loadSharp() {
  try {
    const mod = await import('sharp');
    return mod.default ?? mod;
  } catch {
    return null;
  }
}

async function renderWithSharp(sharp, svg, size) {
  return sharp(Buffer.from(svg)).resize(size, size).png({ compressionLevel: 9 }).toBuffer();
}

// ─── main ───────────────────────────────────────────────────────────────────
async function main() {
  await mkdir(OUT, { recursive: true });
  await mkdir(BUILD, { recursive: true });

  const appSvg = buildAppSvg();
  const monoSvg = buildMonoSvg();
  await writeFile(path.join(OUT, 'aim.svg'), appSvg);
  await writeFile(path.join(OUT, 'aim-mono.svg'), monoSvg);

  let sharp = null;
  if (RENDERER === 'sharp') {
    sharp = await loadSharp();
    if (!sharp) console.warn('sharp is not installed; falling back to the built-in renderer.');
  }
  const renderer = sharp ? 'sharp' : 'builtin';
  console.log(`Renderer: ${renderer}`);

  /** @returns {Promise<Buffer>} PNG bytes */
  async function png(size, mode) {
    if (sharp && mode === 'app') return renderWithSharp(sharp, appSvg, size);
    if (sharp && mode === 'mono') return renderWithSharp(sharp, monoSvg, size);
    return encodePng(renderIcon(size, mode), size, size);
  }

  const appSizes = [1024, 512, 256, 128, 64, 48, 32, 24, 16];
  const appPngs = new Map();
  for (const s of appSizes) {
    const t0 = Date.now();
    appPngs.set(s, await png(s, 'app'));
    console.log(`  app ${s}px (${Date.now() - t0} ms)`);
  }
  await writeFile(path.join(OUT, 'icon.png'), appPngs.get(1024));
  for (const s of appSizes) {
    if (s === 1024 || s === 24) continue;
    await writeFile(path.join(OUT, `icon-${s}.png`), appPngs.get(s));
  }

  const ico = encodeIco([16, 24, 32, 48, 64, 128, 256].map((s) => ({ size: s, png: appPngs.get(s) })));
  await writeFile(path.join(OUT, 'icon.ico'), ico);

  // Tray: colour arrow on transparent background. Windows uses 16 px (1x) / 32 px (2x).
  const tray16 = await png(16, 'tray');
  const tray32 = await png(32, 'tray');
  await writeFile(path.join(OUT, 'tray.png'), tray32);
  await writeFile(path.join(OUT, 'tray@1x.png'), tray16);
  await writeFile(path.join(OUT, 'tray@2x.png'), tray32);
  // macOS template images (white silhouette, alpha only is used by the system).
  await writeFile(path.join(OUT, 'trayTemplate.png'), await png(16, 'mono'));
  await writeFile(path.join(OUT, 'trayTemplate@2x.png'), await png(32, 'mono'));

  // electron-builder resources
  await copyFile(path.join(OUT, 'icon.ico'), path.join(BUILD, 'icon.ico'));
  await copyFile(path.join(OUT, 'icon.png'), path.join(BUILD, 'icon.png'));

  console.log(`Wrote icons to ${path.relative(ROOT, OUT)} and ${path.relative(ROOT, BUILD)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
